// Shared: read .env (no dependency), expose the kit's settings with defaults.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
export const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
export function loadEnv() {
  const f = path.join(root, '.env');
  const env = { ...process.env };
  if (fs.existsSync(f)) for (const line of fs.readFileSync(f, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/); if (m && !(m[1] in process.env)) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  env.PROJECT_NAME = (env.PROJECT_NAME || 'my-app').toLowerCase().replace(/[^a-z0-9-]/g, '-');
  env.PROJECT_STAGE = env.PROJECT_STAGE || 'staging';
  return env;
}
/**
 * ALCHEMY_PASSWORD encrypts Alchemy's local state file. It is a machine value, not a human
 * decision — README and AGENTS.md promise the Cloudflare token and account id are the only keys
 * you must supply, so bootstrap mints this one itself and writes it to .env, where it stays
 * stable. (Before this, a clean `bootstrap --dry-run` reported three blocking issues on a repo
 * whose docs said two values were enough.)
 */
export function ensureAlchemyPassword(env) {
  if (env.ALCHEMY_PASSWORD) return env.ALCHEMY_PASSWORD;
  const pw = crypto.randomBytes(24).toString('base64url');
  const f = path.join(root, '.env');
  const line = `\n# generated by bootstrap — encrypts Alchemy's local state. Keep it; do not commit it.\nALCHEMY_PASSWORD=${pw}\n`;
  if (fs.existsSync(f)) fs.appendFileSync(f, line);
  else fs.writeFileSync(f, `# created by bootstrap${line}`);
  env.ALCHEMY_PASSWORD = pw;
  process.env.ALCHEMY_PASSWORD = pw;
  ok('ALCHEMY_PASSWORD generated and written to .env (keep it stable — it decrypts your state)');
  return pw;
}

export const outputsFile = path.join(root, 'infra/.outputs.json');
export const readOutputs = () => (fs.existsSync(outputsFile) ? JSON.parse(fs.readFileSync(outputsFile, 'utf8')) : null);
export const ok = (m) => console.log(`OK       ${m}`);
export const missing = (m, fix) => { console.log(`MISSING  ${m}`); if (fix) console.log(`FIX:     ${fix}`); };
export const step = (m) => console.log(`\n▶ ${m}`);
